#for string
for item in 'Python':
  print(item)

#list of strings
for item in ['Mosh', 'John', 'Sarah']:
  print(item)

#list of numbers
for item in [1, 2, 3, 4]:
  print(item)
  
#list using range
for item in range(10): #range creates a special type of object... Other examples: range(5, 10), range(5, 10, 2)
  print(item)